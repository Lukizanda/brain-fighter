"""Gather the chosen sounds into one folder, named for upload.

    python tools/sfx/package.py

Reads tools/sfx/chosen.json, copies each chosen render from build/sfx/ to
build/sfx/upload/<name>_v<version>.wav, lints each one, and writes
build/sfx/upload/UPLOAD.md: what each file is for and the steps to upload.
Run render.py first.

The file name becomes the asset's name in Roblox, so it is the name you see
in the Asset Manager and the Creator Hub. The version is in the name because
Roblox cannot replace an uploaded sound: a re-render is a new asset.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from lint import FAIL, lint_file  # noqa: E402

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
BUILD = ROOT / "build" / "sfx"
OUT = BUILD / "upload"


def main() -> int:
    chosen_path = HERE / "chosen.json"
    chosen_doc = json.loads(chosen_path.read_text(encoding="utf-8"))
    chosen = chosen_doc["sounds"]
    recorded = False
    index = json.loads((BUILD / "index.json").read_text(encoding="utf-8"))
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    rows, failed = [], False
    for sound in chosen:
        rel = index["files"].get(sound["kit"], {}).get(sound["cue"])
        if rel is None:
            print(f"FAIL {sound['name']}: {sound['kit']}/{sound['cue']} is not rendered; run render.py")
            failed = True
            continue
        file_name = f"{sound['name']}_v{sound['version']}.wav"
        digest = hashlib.sha256((BUILD / rel).read_bytes()).hexdigest()
        if sound.get("sha256") is None:
            # First packaging since the user chose it: this is the approved sound.
            sound["sha256"] = digest
            recorded = True
        elif sound["sha256"] != digest:
            print(f"FAIL {file_name}: the render no longer matches the sound the user approved "
                  "(the code that makes it changed). Revert that change, or, if it is meant to "
                  "ship, bump `version` and clear `sha256` in chosen.json.")
            failed = True
            continue
        shutil.copyfile(BUILD / rel, OUT / file_name)
        problems = [f for f in lint_file(OUT / file_name) if f[0] == FAIL]
        status = "ready" if not problems else "BLOCKED: " + "; ".join(m for _, _, m in problems)
        failed |= bool(problems)
        uploaded = sound.get("assetId")
        rows.append((file_name, sound["plays_when"], sound["game_hook"], uploaded or "", status))
        print(f"{'ok  ' if not problems else 'FAIL'} {file_name}  ({status})")

    lines = [
        "# Sounds to upload",
        "",
        f"Generated by `tools/sfx/package.py` from `tools/sfx/chosen.json`. {len(rows)} file(s).",
        "",
        "| File | Plays when | Game hook | Asset id | Status |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| `{f}` | {w} | {h} | {a} | {s} |" for f, w, h, a, s in rows]
    lines += [
        "",
        "## Uploading in Studio",
        "",
        "1. Open the Asset Manager (View tab) and use its import button. Select every file in this folder.",
        "2. Keep the names as they are: the name is how the sound is found later.",
        "3. Wait for the sounds to pass moderation. A sound still in review plays only for you.",
        "4. Right-click each sound and copy its asset id. Paste the ids back into the chat, one per file.",
        "",
        "The agent then writes each id into `tools/sfx/chosen.json` and wires the sound into the game.",
        "Skip files that already have an asset id above: they are uploaded.",
    ]
    (OUT / "UPLOAD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if recorded:
        chosen_path.write_text(json.dumps(chosen_doc, indent=2) + "\n", encoding="utf-8")
        print(f"recorded the approved fingerprint of new choices in {chosen_path.name}")
    print(f"wrote {OUT}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
